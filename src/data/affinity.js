export const LEVEL_THRESHOLDS = [0, 5, 15, 30, 50];
export const LEVEL_TITLES = ['새내기', '성장 중', '능숙함', '베테랑', '마스터'];

export function levelForXp(xp) {
  let lvl = 1;
  for (let i = 1; i < LEVEL_THRESHOLDS.length; i++) {
    if (xp >= LEVEL_THRESHOLDS[i]) lvl = i + 1;
  }
  return Math.min(lvl, LEVEL_THRESHOLDS.length);
}

/** 레벨, 다음 레벨까지 진행률(0~1), 다음 레벨 필요 XP */
export function progressForXp(xp) {
  const level = levelForXp(xp);
  if (level >= LEVEL_THRESHOLDS.length) {
    return { level, xp, next: null, progress: 1, title: LEVEL_TITLES[level - 1] };
  }
  const cur = LEVEL_THRESHOLDS[level - 1];
  const next = LEVEL_THRESHOLDS[level];
  return { level, xp, next, progress: (xp - cur) / (next - cur), title: LEVEL_TITLES[level - 1] };
}

